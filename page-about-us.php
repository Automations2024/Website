function Sendnewsletter(event) {
        event.preventDefault();
        var formData = new FormData($('#subscribe-news')[0]);
        console.log(formData);

        var email = $('#emailid').val();
        
        function isValidEmail(email) {
            var regex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;   
            return regex.test(email);
        }

        // Hide the error message initially
        $('#email-validation').hide();

        if (!isValidEmail(email)) {
            $('#email-validation').show(); 
            return;
        }

        $.ajax({
            url: 'https://www.arctrs.com/Subscribe', // API endpoint URL
            method: 'POST',
            data: formData,
            contentType: false,
            processData: false,
            dataType: 'json', // Ensure the response is parsed as JSON
            success: function(response) {
                console.log(response);
                if (response.status == 400) {
                    toastr.success(response.message); // Display error message if status is 400
                } else if (response.status == 201) {
                    toastr.success('Thank you for subscribing to our newsletter! You are now connected to the latest updates, news, and offers from Arcturus Consulting Services Inc. Expect exciting content delivered straight to your inbox. Stay tuned for exclusive promotions and valuable insights. Welcome aboard!');
                    // Close the modal after a successful subscription
                    $('#email_popup_id').modal('hide');
                } else {
                    toastr.error(response.message); // Handle any other statuses
                }
            },
            error: function(xhr, status, error) {
                // Set error message to session storage
                sessionStorage.setItem('careerFormErrorMessage', 'Unsubscribe: ' + error);
                console.error('API call error:', error);
                toastr.error('Failed to subscribe. Please try again later.');
                // Optionally, reload the page on error
                // location.reload();
            }
        });
    }






